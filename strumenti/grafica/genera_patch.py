"""Generate the installer's graphics patch from an original Shivah.exe.

Usage: python strumenti/grafica/genera_patch.py "<path to original Shivah.exe>"

Writes:
  installer/files/grafica.bin   new pixel data of the translated sprites
  installer/grafica.nsh         exe size, Adler-32 checksums and patch ranges
The original pixel data is not stored: the installer recognises the original
and the patched executable by the checksums of the patched ranges.
"""
import json
import os
import subprocess
import sys
import tempfile
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
INSTALLER = os.path.join(HERE, "..", "..", "installer")


def adler(data):
    v = zlib.adler32(data)
    return v & 0xFFFF, v >> 16  # (a, s) as computed by the installer


def main():
    exe = sys.argv[1]
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, os.path.join(HERE, "graphics.py"), exe, tmp], check=True)
        info = json.load(open(os.path.join(tmp, "ranges.json")))
        old = open(os.path.join(tmp, "old.bin"), "rb").read()
        new = open(os.path.join(tmp, "new.bin"), "rb").read()
    open(os.path.join(INSTALLER, "files", "grafica.bin"), "wb").write(new)
    a0, s0 = adler(old)
    a1, s1 = adler(new)
    lines = [
        "; Generated by strumenti/grafica/genera_patch.py - do not edit",
        f"!define GFX_EXE_SIZE {info['exe_size']}",
        f"!define GFX_ORIG_A {a0}",
        f"!define GFX_ORIG_S {s0}",
        f"!define GFX_NEW_A {a1}",
        f"!define GFX_NEW_S {s1}",
        "",
        "; Each range: file offset, length (sprite number in the comment)",
        "!macro GFX_RANGES MACRO",
    ]
    for off, n, i in info["ranges"]:
        lines.append(f"  !insertmacro ${{MACRO}} {off} {n} ; sprite {i}")
    lines.append("!macroend")
    open(os.path.join(INSTALLER, "grafica.nsh"), "w", encoding="utf-8", newline="\r\n").write("\n".join(lines) + "\n")
    print(f"{len(info['ranges'])} ranges, {len(new)} bytes; original adler {a0}/{s0}, patched {a1}/{s1}")


if __name__ == "__main__":
    main()
